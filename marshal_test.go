package client

import (
	"encoding/json"
	"testing"
	"time"

	"github.com/manrs-tools/manrs-observatory-go/model"
)

func marshalJSON(t *testing.T, v any) string {
	t.Helper()

	c := New("test-key")

	b, err := c.marshal(v)
	if err != nil {
		t.Fatalf("marshal returned an error: %v", err)
	}

	return string(b)
}

func TestMarshalOmitsReadOnlyFields(t *testing.T) {
	tests := []struct {
		name  string
		input any
		want  string
	}{
		{
			// The server assigns id/created/userID, and rejects a zero-valued id as a bad UUID.
			name:  "favorite drops server-assigned fields",
			input: map[string]*model.Favorite{"favorite": {Name: "x", Selection: "europe,ripe"}},
			want:  `{"favorite":{"name":"x","selection":"europe,ripe"}}`,
		},
		{
			// A favorite read back from the API and resent must not carry its id back.
			name: "favorite drops populated read-only fields too",
			input: map[string]*model.Favorite{"favorite": {
				ID:      "01a033dd-c80c-7eca-bdab-1ee33877c6d9",
				UserID:  "019eccd4-bbe5-7670-ba1e-4e88ba87051f",
				Created: time.Date(2026, 8, 24, 13, 2, 47, 0, time.UTC),
				Name:    "x", Selection: "europe,ripe",
			}},
			want: `{"favorite":{"name":"x","selection":"europe,ripe"}}`,
		},
		{
			name:  "api key drops created/id/autoGenerated",
			input: map[string]*model.APIKey{"key": {Description: "d", Expiry: time.Date(2027, 1, 1, 0, 0, 0, 0, time.UTC)}},
			want:  `{"key":{"description":"d","expiry":"2027-01-01T00:00:00Z"}}`,
		},
		{
			name:  "writable zero values are still sent",
			input: map[string]*model.Favorite{"favorite": {Name: "", Selection: ""}},
			want:  `{"favorite":{"name":"","selection":""}}`,
		},
		{
			name:  "omitempty is still honoured",
			input: map[string]*model.FavoriteFilter{"filter": {Limit: 0}},
			want:  `{"filter":{}}`,
		},
		{
			name:  "nil pointer fields stay nil",
			input: map[string]*model.FavoriteUpdate{"update": {Name: nil}},
			want:  `{"update":{}}`,
		},
		{
			name:  "nil maps encode as null",
			input: map[string]model.Declaration{"declaration": nil},
			want:  `{"declaration":null}`,
		},
		{
			name:  "empty maps encode as an empty object",
			input: map[string]map[string]string{"labels": {}},
			want:  `{"labels":{}}`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := marshalJSON(t, tt.input); got != tt.want {
				t.Errorf("marshal =\n  %s\nwant\n  %s", got, tt.want)
			}
		})
	}
}

func TestMarshalPreservesSelfEncodingTypes(t *testing.T) {
	// Timestamps have only unexported fields; walking one as a struct would erase it.
	expiry := time.Date(2027, 3, 4, 5, 6, 7, 0, time.UTC)

	got := marshalJSON(t, map[string]*model.APIKey{"key": {Description: "d", Expiry: expiry}})

	var body struct {
		Key struct {
			Expiry time.Time `json:"expiry"`
		} `json:"key"`
	}

	if err := json.Unmarshal([]byte(got), &body); err != nil {
		t.Fatalf("result is not valid JSON: %v (%s)", err, got)
	}

	if !body.Key.Expiry.Equal(expiry) {
		t.Errorf("expiry round-tripped as %v, want %v (raw: %s)", body.Key.Expiry, expiry, got)
	}
}

func TestMarshalPromotesEmbeddedStructs(t *testing.T) {
	// ROAStatsDetail embeds ROAStats, and encoding/json inlines those fields rather than
	// nesting them under the type name.
	got := marshalJSON(t, &model.ROAStatsDetail{
		ROAStats:    model.ROAStats{Total: 7, Valid: 5},
		DateFetched: "2026-08-24",
	})

	var body map[string]any
	if err := json.Unmarshal([]byte(got), &body); err != nil {
		t.Fatalf("result is not valid JSON: %v (%s)", err, got)
	}

	if _, nested := body["ROAStats"]; nested {
		t.Errorf("embedded struct was nested instead of promoted: %s", got)
	}

	if body["total"] != float64(7) {
		t.Errorf("embedded field total = %v, want 7 (raw: %s)", body["total"], got)
	}
}

func TestMarshalMatchesEncodingJSONForWritableFields(t *testing.T) {
	// Everything except the read-only fields should serialise exactly as encoding/json would.
	update := &model.FavoriteUpdate{}
	name := "Renamed"
	update.Name = &name

	got := marshalJSON(t, map[string]*model.FavoriteUpdate{"update": update})

	want, err := json.Marshal(map[string]*model.FavoriteUpdate{"update": update})
	if err != nil {
		t.Fatalf("reference marshal failed: %v", err)
	}

	if got != string(want) {
		t.Errorf("marshal = %s, want %s", got, want)
	}
}
